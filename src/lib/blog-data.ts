export async function getPublishedPostCardsByCategoryAsync(
  category: BlogCategory,
  now: Date = new Date()
): Promise<BlogCardMeta[]> {
  const all = await getPublishedPostCardsAsync(now);
  return all.filter((c) => c.category === category);
}

